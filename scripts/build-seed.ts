// Builds supabase/seed.sql from supabase/seed/docs/* (ROADMAP 1.6).
// Run: npm run seed:build   — then `npx supabase db reset` loads it.
//
// Simulates the upload pipeline: content is passed through redact() and pii_summary stores counts only.
// Files 01–03 are public + approved, 04–05 internal + approved. Each internal document must carry exactly
// one unique canary code (CANARY-INT-xxxx, SEC-02); public documents must carry none.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { redact } from "../lib/privacy/redact";

const ROOT = path.resolve(__dirname, "..");
const DOCS = path.join(ROOT, "supabase/seed/docs");
const OUT = path.join(ROOT, "supabase/seed.sql");
const CANARY = /CANARY-INT-[A-Z0-9]{4}/g;
const PUBLIC_PREFIXES = ["01-", "02-", "03-"];

interface Acara {
  name: string;
  slug: string;
  event_date: string;
  location: string;
  contact_public: string;
}

/** Deterministic UUID so ids stay stable across resets (handy for manual testing). */
function uuidFor(key: string): string {
  const h = createHash("sha256").update(`panitiapintar-seed:${key}`).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const sha256 = (s: string) => createHash("sha256").update(s).digest("hex");

const USERS = [
  { key: "superadmin", email: "superadmin@contoh.test", name: "Super Admin Contoh", superAdmin: true },
  { key: "admin-festek", email: "admin.festek@contoh.test", name: "Admin Festek Contoh" },
  { key: "admin-lomba", email: "admin.lomba@contoh.test", name: "Admin Lomba Contoh" },
  { key: "admin-seminar", email: "admin.seminar@contoh.test", name: "Admin Seminar Contoh" },
  { key: "anggota-festek", email: "anggota.festek@contoh.test", name: "Anggota Festek Contoh" },
] as const;

const MEMBERSHIPS: Record<string, Array<[string, "admin" | "member"]>> = {
  "festival-teknologi-fiktif": [
    ["admin-festek", "admin"],
    ["anggota-festek", "member"],
  ],
  "lomba-desain-fiktif": [["admin-lomba", "admin"]],
  "seminar-karier-fiktif": [["admin-seminar", "admin"]],
};

const ADMIN_OF: Record<string, string> = {
  "festival-teknologi-fiktif": "admin-festek",
  "lomba-desain-fiktif": "admin-lomba",
  "seminar-karier-fiktif": "admin-seminar",
};

export function buildSeed(): string {
  const sql: string[] = [
    "-- GENERATED by scripts/build-seed.ts from supabase/seed/docs/. Do not edit by hand.",
    "-- Dummy data only (3 fictional events, @contoh.test accounts).",
    "begin;",
    "",
    "-- Accounts (magic link only, no password).",
  ];

  for (const u of USERS) {
    const id = uuidFor(`user:${u.key}`);
    sql.push(
      `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,` +
        ` raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token,` +
        ` email_change_token_new, email_change) values ('00000000-0000-0000-0000-000000000000', ${q(id)},` +
        ` 'authenticated', 'authenticated', ${q(u.email)}, '', now(), '{"provider":"email","providers":["email"]}',` +
        ` '{}', now(), now(), '', '', '', '');`,
      `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at,` +
        ` updated_at) values (${q(uuidFor(`identity:${u.key}`))}, ${q(id)}, ${q(id)},` +
        ` jsonb_build_object('sub', ${q(id)}, 'email', ${q(u.email)}), 'email', now(), now(), now());`,
      `insert into profiles (user_id, display_name, is_super_admin) values (${q(id)}, ${q(u.name)},` +
        ` ${"superAdmin" in u && u.superAdmin ? "true" : "false"});`,
    );
  }

  const seenCanaries = new Set<string>();
  sql.push("", "-- Approving seed documents goes through the same guard flag as approve_document().");
  sql.push("select set_config('app.doc_rpc', 'on', true);");

  for (const dir of readdirSync(DOCS, { withFileTypes: true }).filter((d) => d.isDirectory())) {
    const folder = path.join(DOCS, dir.name);
    const acara = JSON.parse(readFileSync(path.join(folder, "_acara.json"), "utf8")) as Acara;
    if (acara.slug !== dir.name) throw new Error(`slug mismatch in ${dir.name}`);
    const committeeId = uuidFor(`committee:${acara.slug}`);
    const adminId = uuidFor(`user:${ADMIN_OF[acara.slug]}`);

    sql.push(
      "",
      `-- ${acara.name}`,
      `insert into committees (id, name, slug, event_date, location, contact_public, status, created_by) values` +
        ` (${q(committeeId)}, ${q(acara.name)}, ${q(acara.slug)}, ${q(acara.event_date)}, ${q(acara.location)},` +
        ` ${q(acara.contact_public)}, 'active', ${q(uuidFor("user:superadmin"))});`,
    );
    for (const [userKey, role] of MEMBERSHIPS[acara.slug] ?? []) {
      sql.push(
        `insert into memberships (user_id, committee_id, role) values (${q(uuidFor(`user:${userKey}`))},` +
          ` ${q(committeeId)}, '${role}');`,
      );
    }

    const files = readdirSync(folder)
      .filter((f) => f.endsWith(".md"))
      .sort();
    for (const file of files) {
      const raw = readFileSync(path.join(folder, file), "utf8");
      const isPublic = PUBLIC_PREFIXES.some((p) => file.startsWith(p));
      const canaries = new Set(raw.match(CANARY) ?? []);
      if (isPublic && canaries.size > 0) throw new Error(`${dir.name}/${file}: public doc contains a canary`);
      if (!isPublic) {
        if (canaries.size !== 1) throw new Error(`${dir.name}/${file}: internal doc needs exactly one canary`);
        const [code] = canaries;
        if (seenCanaries.has(code)) throw new Error(`${dir.name}/${file}: canary ${code} is not unique`);
        seenCanaries.add(code);
      }

      const title = (raw.match(/^#\s+(.+)$/m)?.[1] ?? file).trim().slice(0, 150);
      const { text, found } = redact(raw);
      if (isPublic && Object.keys(found).length > 0) {
        throw new Error(`${dir.name}/${file}: public doc contains PII patterns ${Object.keys(found).join(",")}`);
      }
      const docId = uuidFor(`doc:${acara.slug}/${file}`);
      const versionId = uuidFor(`version:${acara.slug}/${file}`);
      const visibility = isPublic ? "public" : "internal";

      sql.push(
        `insert into documents (id, committee_id, title, visibility, status, storage_path, mime_type, size_bytes,` +
          ` sha256, pii_summary, uploaded_by) values (${q(docId)}, ${q(committeeId)}, ${q(title)},` +
          ` '${visibility}', 'uploaded', ${q(`${committeeId}/${docId}`)}, 'text/markdown',` +
          ` ${Buffer.byteLength(raw)}, ${q(sha256(raw))}, ${q(JSON.stringify(found))}::jsonb, ${q(adminId)});`,
        `insert into document_versions (id, document_id, kind, content, created_by) values (${q(versionId)},` +
          ` ${q(docId)}, 'ai_refined', ${q(text)}, null);`,
        `update documents set status = 'approved', current_version_id = ${q(versionId)}, approved_by = ${q(adminId)},` +
          ` approved_at = now() where id = ${q(docId)};`,
        `insert into audit_logs (actor_id, actor_role, action, target_type, target_id, committee_id, outcome,` +
          ` metadata, request_id) values (${q(adminId)}, 'admin', 'document.approve', 'document', ${q(docId)},` +
          ` ${q(committeeId)}, 'success', '{"seed":true}', null);`,
      );
      if (visibility === "public") {
        sql.push(
          `insert into audit_logs (actor_id, actor_role, action, target_type, target_id, committee_id, outcome,` +
            ` metadata, request_id) values (${q(adminId)}, 'admin', 'document.visibility.changed', 'document',` +
            ` ${q(docId)}, ${q(committeeId)}, 'success', '{"seed":true,"to":"public"}', null);`,
        );
      }
    }
  }

  sql.push("", "select set_config('app.doc_rpc', 'off', true);", "commit;", "");
  return sql.join("\n");
}

if (require.main === module) {
  writeFileSync(OUT, buildSeed());
  process.stdout.write(`wrote ${path.relative(ROOT, OUT)}\n`);
}
